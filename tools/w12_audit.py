def stage_pii(_args):
    """What the MCP servers hand over, probed exhaustively; what the logs hold."""

    from w12_agent import TriageSession

    session = TriageSession()
    responses = []

    try:
        for claim in CLAIMS:

            responses.append(("get_fnol", session.clients["claims-records"].call_tool(
                "get_fnol", {"claim_number": claim["claim_number"]})))
            responses.append(("lookup_policy", session.clients["claims-records"].call_tool(
                "lookup_policy", {"policy_number": claim["policy_number"]})))
            responses.append(("check_coverage_in_force", session.clients["claims-records"].call_tool(
                "check_coverage_in_force",
                {"policy_number": claim["policy_number"], "loss_date": claim["loss_date"]})))
            responses.append(("get_limits", session.clients["policy-wording"].call_tool(
                "get_limits", {"policy_number": claim["policy_number"], "loss_date": claim["loss_date"],
                               "peril_class": claim["truth"]["peril_class"]})))

        # Bait: a search written to pull the claimant out of the wording index,
        # which holds no claimant data and must return none.
        for claim in CLAIMS[:6]:
            responses.append(("search_policy_wording", session.clients["policy-wording"].call_tool(
                "search_policy_wording",
                {"query": f"{claim['claimant_name']} {claim['address']} injury", "product": "household",
                 "loss_date": claim["loss_date"]})))
    finally:
        session.close()

    wire_hits = [(tool, find_pii(json.dumps(payload))) for tool, payload in responses]
    wire_leaks = [(t, h) for t, h in wire_hits if h]

    # The wire guard itself: a server that DOES put PII in a response must
    # have it withheld. Tested in-process on a throwaway server.
    from w12_mcp import TracedMCPServer
    from w9d_mcp import Tool

    probe = TracedMCPServer("probe", wire_guard=find_pii)
    victim = CLAIMS[0]
    probe.add_tool(Tool("leaky", "returns raw PII", {"type": "object"},
                        lambda args: {"note": f"{victim['claimant_name']} lives at {victim['address']}"}))
    reply = probe._handle({"jsonrpc": "2.0", "id": 1, "method": "tools/call",
                           "params": {"name": "leaky", "arguments": {}}})
    guard_blocked = (reply["result"]["isError"]
                     and not find_pii(reply["result"]["content"][0]["text"]))

    # What the logs hold.
    log_files = sorted((REPO_ROOT / "traces").glob("w12_*.jsonl")) + [REPO_ROOT / "traces" / "requests.jsonl"]
    log_leaks = []
    log_lines = 0

    for path in log_files:
        if not path.exists():
            continue
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            log_lines += 1
            hits = [h for h in find_pii(line) if h.lower() not in
                    ("hospital", "burn", "burned", "burnt")]
            if hits:
                log_leaks.append((path.name, number, hits[:3]))

    lines = ["# PII audit - what leaves the system", "",
             f"- MCP responses probed: **{len(responses)}** (every tool, every one of the {len(CLAIMS)} claims, "
             f"plus 6 search queries written to pull a claimant out of the index)",
             f"- known PII literals searched for in each: **{len(__import__('w12_pii').ALL_LITERALS)}** "
             f"(claimant names and name parts, addresses, injury sentences) plus an injury-word lexicon",
             f"- **PII found in MCP responses: {len(wire_leaks)}**",
             f"- wire guard test (a tool that returns a raw name + address): "
             f"{'withheld and replaced with an error' if guard_blocked else 'NOT WITHHELD - FAILURE'}",
             f"- log lines scanned: **{log_lines}** across {len([p for p in log_files if p.exists()])} files",
             f"- **PII found in logs: {len(log_leaks)}**"]

    if wire_leaks:
        lines += ["", "Leaks in MCP responses:"] + [f"- {t}: {h}" for t, h in wire_leaks[:10]]

    if log_leaks:
        lines += ["", "Leaks in logs:"] + [f"- {f}:{n} {h}" for f, n, h in log_leaks[:10]]

    sample = next(p for t, p in responses if t == "get_fnol")
    lines += ["", "What `get_fnol` hands another squad's agent, for claim "
              f"{CLAIMS[0]['claim_number']} (the claim file also holds {CLAIMS[0]['claimant_name']!r}, "
              f"{CLAIMS[0]['address']!r}"
              + (f", and an injury sentence" if CLAIMS[0]["injury"] else "") + "):", "", "```json",
              json.dumps(sample, indent=2), "```"]

    text = "\n".join(lines)
    print(text)
    (OUT_DIR / "pii_audit.md").write_text(text + "\n", encoding="utf-8")


