def stage_trace(args):

    run = load_run(args.label)
    span_log = REPO_ROOT / "traces" / "w12_mcp_spans.jsonl"
    server_rows = [json.loads(l) for l in span_log.read_text().splitlines() if l.strip()] if span_log.exists() else []
    by_trace = defaultdict(list)

    for row in server_rows:
        by_trace[row["trace_id"]].append(row)

    request_log = REPO_ROOT / "traces" / f"w12_requests_{args.label}.jsonl"
    logged = {}

    for line in request_log.read_text(encoding="utf-8").splitlines():
        record = json.loads(line)
        logged[record["trace_id"]] = record

    failures = []

    for case_id, result in run.items():

        tid = result["trace_id"]
        record = logged.get(tid)
        mcp_calls = [c for c in result["tool_calls"] if c["server"] and not c.get("cached")]
        problems = []

        if record is None:
            problems.append("no request-log line")
        else:
            if (record.get("output") or {}).get("trace_id") not in (None, tid):
                problems.append("referral carries a different trace id")
            if len(by_trace[tid]) != len(mcp_calls):
                problems.append(f"{len(mcp_calls)} MCP calls but {len(by_trace[tid])} server spans on disk")
            if len(record["extra"]["server_spans"]) != len(mcp_calls):
                problems.append("server spans missing from the request log")
            if any("cost_usd" not in s or "latency_ms" not in s for s in record["spans"]):
                problems.append("span without a cost field")

        if problems:
            failures.append((case_id, tid, problems))

    n = len(run)
    lines = ["# Trace continuity - one trace id, FNOL in to referral out", "",
             f"- requests checked: **{n}**; requests whose id survived the agent hop *and* the MCP hop "
             f"with every server span accounted for: **{n - len(failures)}/{n}**",
             "- checks per request: request-log line exists; referral trace id == log trace id; "
             "every MCP call has a server span on disk under the same id; the server spans are also "
             "folded into the request log; every span carries latency, tokens and cost"]

    for case_id, tid, problems in failures[:10]:
        lines.append(f"- FAIL {case_id} `{tid}`: {'; '.join(problems)}")

    sample_id = next(iter(run.values()))["trace_id"]
    sample = logged[sample_id]

    lines += ["", f"Example, `{sample_id}` (case {next(iter(run))}):", "", "| span | stage | latency ms | tokens in/out | cost USD | server ms |",
              "|---|---|---|---|---|---|"]

    for span in sample["spans"]:
        lines.append(f"| {span['name']} | {span['stage']} | {span['latency_ms']} | "
                     f"{span['tokens_in']}/{span['tokens_out']} | {span['cost_usd']:.6f} | "
                     f"{span['attrs'].get('server_latency_ms', '-')} |")

    text = "\n".join(lines)
    print(text)
    (OUT_DIR / "trace_continuity.md").write_text(text + "\n", encoding="utf-8")


