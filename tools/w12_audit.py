def stage_replay(args):
    """
    Re-run a logged request's retrieval and prove the context is identical.

    What this can and cannot prove. It proves the *inputs* to the answer are
    reproducible: the same wording editions, the same retrieved chunk ids
    and the same chunk text (by hash), under the same prompt hash and model
    id. It does not prove the model would re-generate the same sentences -
    a sampled model does not promise that - so the logged output is the
    record of what was said, and the replay is the proof of what it was
    said *from*.
    """

    from w12_retrieval import search_wording

    request_log = REPO_ROOT / "traces" / f"w12_requests_{args.label}.jsonl"
    record = next(json.loads(l) for l in request_log.read_text(encoding="utf-8").splitlines()
                  if json.loads(l)["trace_id"] == args.trace)

    searches = [c for c in record["extra"]["tool_calls"] if c["name"] == "search_policy_wording"]
    logged = record["extra"]["retrieved"]

    replayed = []

    for call in searches:
        a = call["args"]
        # Replay under the retrieval version the request was logged with. The
        # first replay of this very trace came back "not identical" because
        # retrieval had since gained pair completion (v2) and the replay used
        # today's code - which is the check working: it caught that "same
        # retrieved context" no longer holds for the current code, and the
        # request log's `retrieval_version` is what makes the old behaviour
        # reproducible instead of lost.
        version = record["retrieval_version"]
        result = search_wording(a["query"], a["product"], a["loss_date"],
                                top_k=a.get("top_k") or 3,
                                date_filter=version != "hybrid-nofilter",
                                complete_pairs=version not in ("hybrid-datefilter-v1", "hybrid-nofilter"))
        replayed += [{"chunk_id": m["chunk_id"], "form_number": m["form_number"],
                      "edition_date": m["edition_date"],
                      "text_sha256": hashlib.sha256(m["text"].encode()).hexdigest()[:16]}
                     for m in result["matches"]]

    same = replayed == logged

    lines = [f"# Replay of `{args.trace}`", "",
             f"- model: `{record['model']}`; prompt: `{record['prompt_version']}` sha256 `{record['input']['prompt_sha256']}`; "
             f"retrieval: `{record['retrieval_version']}`",
             f"- searches re-run: {len(searches)}; chunks logged: {len(logged)}; chunks replayed: {len(replayed)}",
             f"- **retrieved context identical (ids, editions, text hash): {same}**", "",
             "| chunk | edition | text hash | replayed match |", "|---|---|---|---|"]

    for entry, again in zip(logged, replayed + [None] * len(logged)):
        lines.append(f"| {entry['chunk_id'][:34]} | {entry['form_number']} {entry['edition_date']} | "
                     f"`{entry['text_sha256']}` | {again == entry} |")

    lines += ["", "Not proven here, stated plainly: that the model would reproduce the same sentences. "
              "The logged referral is the record of what was said; this replay proves what it was said from."]

    text = "\n".join(lines)
    print(text)
    (OUT_DIR / f"replay_{args.trace}.md").write_text(text + "\n", encoding="utf-8")


