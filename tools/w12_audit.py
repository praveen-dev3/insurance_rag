# loss family by case id, read from the claims module's rows
FAMILY_OF = {row[0]: row[1] for row in ROWS}


def _is_expected(chunk, form, edition, clause):

    if chunk["form_number"] != form or chunk["edition_date"] != edition:
        return False

    if clause.upper().startswith("E-"):
        return clause.upper() in [c.upper() for c in chunk["exclusion_codes"]]

    return bool(re.search(rf"(?m)(^|\s){re.escape(clause)}\s", chunk["text"]))


