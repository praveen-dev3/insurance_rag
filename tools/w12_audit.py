def _citable(match, clause):
    return clause.upper() in [c.upper() for c in match["cite_as"]]


def stage_groundability(args):
    """
    Replay every logged search of a run under retrieval with and without the
    fix, and ask two deterministic questions of each request:

      * groundable - is every clause the model cited present in what the
        replayed searches returned? (a clause the model was never shown is
        a clause it invented or inferred from a cross-reference)
      * reachable  - is every expected clause for this loss present in what
        the replayed searches returned? (retrieval's half of "right clause")

    Replaying the *model's own logged queries* is what makes this a test of
    retrieval alone: the model's behaviour is held fixed at what it did, so
    any change in the numbers is the retrieval change and nothing else. The
    agent-level confirmation (does the model now cite the clause it is
    shown) needs LLM tokens and is a separate, resumable run.
    """

    from w12_retrieval import search_wording

    run = load_run(args.label)
    arms = {"RED (pair completion off)": False, "GREEN (pair completion on)": True}
    table = {}

    for arm, flag in arms.items():

        rows = []

        for case_id, result in run.items():

            referral = result["referral"]
            claim = CLAIMS_BY_CASE[case_id]

            if not referral or claim["truth"]["boundary"] in ("lapsed",):
                continue

            matches = []

            for call in result["tool_calls"]:
                if call["name"] != "search_policy_wording" or not call["ok"]:
                    continue
                a = call["args"]
                matches += search_wording(a["query"], a["product"], a["loss_date"],
                                          top_k=a.get("top_k") or 3, date_filter=True,
                                          complete_pairs=flag)["matches"]

            cites = referral["citations"]
            groundable = all(any(m["form_number"] == c["form_number"] and m["edition_date"] == c["edition_date"]
                                 and _citable(m, c["clause"]) for m in matches) for c in cites)
            expected = claim["truth"]["expected_cites"]
            reachable = (all(any(m["form_number"] == f and m["edition_date"] == e and _citable(m, cl)
                                 for m in matches) for f, e, cl in expected) if expected else None)
            stale = any(m["edition_date"] != editions_for_product(
                POLICIES[claim["policy_number"]]["product"], claim["loss_date"]).get(m["form_number"])
                for m in matches if m["form_number"] in ("HO-0850", "MO-0420"))

            rows.append({"case_id": case_id, "boundary": claim["truth"]["boundary"],
                         "groundable": groundable, "reachable": reachable, "stale": stale,
                         "passage_count": len(matches)})

        table[arm] = rows

    def counts(rows):
        ground = sum(r["groundable"] for r in rows)
        reach = [r for r in rows if r["reachable"] is not None]
        both = sum(1 for r in rows if r["groundable"] and r["reachable"] is not False)
        return ground, len(rows), sum(r["reachable"] for r in reach), len(reach), both,             sum(r["stale"] for r in rows), sum(r["passage_count"] for r in rows) / max(len(rows), 1)

    lines = [f"# Week 12 closed loop - groundable citations (retrieval replay, LLM-free)", "",
             "Failure under test: the model cited a clause that retrieval never returned "
             "(`ungrounded_citation`, 3 of 25 integrated requests, e.g. `req-e1aceef67b4b`). "
             "Diagnosis from the logged context ids: the exclusion-table chunks filled the top 3 and the "
             "`2. Coverage Basis` chunk was not among them. Fix: retrieval layer, "
             "`_complete_pairs` in tools/w12_retrieval.py (retrieval version "
             "`hybrid-datefilter-v1` -> `hybrid-datefilter-v2`).", "",
             f"Replayed: every logged search of run `{args.label}`, the model's own queries, unchanged.", "",
             "| arm | requests with every cited clause groundable | expected clause reachable | "
             "case passes both | stale-edition passages | mean passages/request |",
             "|---|---|---|---|---|---|"]

    for arm, rows in table.items():
        g, gn, r, rn, both, stale, mean_p = counts(rows)
        lines.append(f"| {arm} | {g}/{gn} | {r}/{rn} | {both}/{gn} | {stale} | {mean_p:.1f} |")

    red_rows = {r["case_id"]: r for r in table["RED (pair completion off)"]}
    green_rows = {r["case_id"]: r for r in table["GREEN (pair completion on)"]}

    lines += ["", "Per-case changes (RED -> GREEN):", ""]
    changed = False

    for case_id, red in red_rows.items():
        green = green_rows[case_id]
        if (red["groundable"], red["reachable"]) != (green["groundable"], green["reachable"]):
            changed = True
            lines.append(f"- {case_id} ({red['boundary']}): groundable {red['groundable']} -> {green['groundable']}, "
                         f"reachable {red['reachable']} -> {green['reachable']}")

    regress = [c for c, red in red_rows.items()
               if (red["groundable"] and not green_rows[c]["groundable"])
               or (red["reachable"] and green_rows[c]["reachable"] is False)]

    lines += ["" if changed else "- (no per-case change)",
              f"Cases that were fine and are now not (silent regressions): **{len(regress)}** {regress or ''}"]

    text = "\n".join(lines)
    print(text)
    (OUT_DIR / "closed_loop_groundability.md").write_text(text + "\n", encoding="utf-8")


