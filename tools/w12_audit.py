JUDGE_PROMPT = """You are auditing one referral written by an AI claims-triage assistant. The assistant must NOT decide
coverage; it surfaces policy wording and facts for a human adjuster.

Decide ONE thing: wording_faithful.

wording_faithful is TRUE only if ALL hold:
  * every factual statement in the SUMMARY and in each citation's RELEVANCE is supported by the CITED WORDING
    blocks or by the CLAIM FACTS shown below;
  * the SUMMARY does not state, imply or hedge a coverage decision (covered, excluded, payable, declined, or a
    "likely"/"appears" version of the same) - describing what a clause says is fine, saying what it means for
    this claim's outcome is not;
  * every wording passage named was retrieved for the loss date shown and its edition is stated;
  * it does not assert a deductible, sub-limit or policy limit that is not in FIGURES, and does not mix the
    three up.

Judge only these. Not style, completeness or whether you would have cited something else.

Reply with exactly one JSON object: {"wording_faithful": true|false, "reason": "<one sentence>"}"""


def _judge_input(claim, result, version="v2"):

    referral = result["referral"] or {}
    cited = "\n".join(
        f"[{c['form_number']} ed. {c['edition_date']} clause {c['clause']}, loss date {c.get('loss_date_resolved')}] "
        f"{c.get('wording_excerpt')}" for c in referral.get("citations", []))

    # v1 gave the judge the policy number, loss date and in-force flag only,
    # so every sentence in a summary describing the loss itself ("river water
    # entered the ground floor") was "unsupported" by construction - 6 of its
    # 25 verdicts. v2 adds the same redacted account of the loss the agent was
    # given, which is a fix to what the judge was shown, not to what it was
    # asked.
    facts = (f"policy {claim['policy_number']}, loss date {claim['loss_date']}, "
             f"in force: {referral.get('in_force')}.")

    if version == "v2":
        from w12_pii import redact_narrative
        facts += f" Redacted account of the loss: {redact_narrative(claim)}"

    return (f"{JUDGE_PROMPT}\n\nCLAIM FACTS: {facts}\n\nCITED WORDING:\n{cited or '(none)'}\n\n"
            f"FIGURES: {json.dumps(referral.get('figures'))}\n\nSUMMARY: {referral.get('summary')}\n\n"
            "RELEVANCE: " + " | ".join(c.get("relevance", "") for c in referral.get("citations", [])))


def stage_judge(args):
    """
    Judge every referral of a run. Resumable, and throttled to the model's limits.

    qwen/qwen3.8-27b on the free tier allows 1,000 *output* tokens a minute and
    rejects any request whose max_tokens could exceed what is left, so the
    call sets a small max_tokens and the loop saves after every verdict - a
    rejected 14th call must not discard the first 13.
    """

    from w7d_common import call_llm

    run = load_run(args.label)
    model = args.judge_model
    path = OUT_DIR / f"judge_{args.label}_{args.judge_version}_{args.judge_reasoning}.json"
    verdicts = json.loads(path.read_text())["verdicts"] if path.exists() else {}

    def save(complete):
        path.write_text(json.dumps(
            {"judge_model": model, "judge_version": args.judge_version, "complete": complete,
             "judge_prompt_sha256": hashlib.sha256(JUDGE_PROMPT.encode()).hexdigest()[:16],
             "verdicts": verdicts}, indent=2), encoding="utf-8")

    for case_id, result in run.items():

        if case_id in verdicts:
            continue

        if not result["referral"]:
            verdicts[case_id] = {"wording_faithful": False, "reason": "no referral"}
            continue

        # One re-ask for an output that is not the requested object (it
        # happens: a verdict came back as {"in": true, ...}). A second bad
        # answer is recorded as no verdict, which the agreement counts as a
        # disagreement rather than being quietly dropped.
        for attempt in range(2):
            response = call_llm(model=model, messages=[
                {"role": "user", "content": _judge_input(CLAIMS_BY_CASE[case_id], result, args.judge_version)}],
                reasoning_effort=args.judge_reasoning, max_tokens=450)
            text = response.choices[0].message.content or ""
            match = re.search(r"\{.*\}", text, re.S)

            try:
                parsed = json.loads(match.group(0))
            except (AttributeError, json.JSONDecodeError):
                parsed = {}

            if isinstance(parsed.get("wording_faithful"), bool):
                break

            parsed = {"wording_faithful": None, "reason": f"unparseable: {text[:80]}"}

        verdicts[case_id] = parsed
        save(False)
        print(f"  {case_id}: {parsed}", flush=True)

        # At most 450 output tokens per call against a 1,000/minute cap: with
        # reasoning off a verdict is ~50 tokens, with it on the reasoning alone
        # can fill the budget and leave an empty answer.
        time.sleep(30 if args.judge_reasoning != "none" else 4)

    save(True)


def stage_agreement(args):

    labels_path = OUT_DIR / f"labels_{args.label}.json"
    labels = json.loads(labels_path.read_text())["labels"]
    verdicts = json.loads((OUT_DIR / f"judge_{args.label}_{args.judge_version}_{args.judge_reasoning}.json").read_text())["verdicts"]

    cells = defaultdict(int)
    disagree = []

    for case_id, label in labels.items():
        judge = verdicts[case_id]["wording_faithful"]
        cells[(label, judge)] += 1

        if judge is not label:
            disagree.append((case_id, label, judge, verdicts[case_id]["reason"]))

    n = len(labels)
    agree = n - len(disagree)

    lines = [f"# Judge agreement on the integrated system's outputs (judge {args.judge_version}, reasoning {args.judge_reasoning})", "",
             f"- cases hand-labelled: **{n}**; judge agrees on **{agree}/{n} = {agree / n:.1%}**",
             f"- bar from the brief: 85% -> **{'CLEARED' if agree / n >= 0.85 else 'NOT CLEARED'}**", "",
             "| label \\ judge | faithful | unfaithful |", "|---|---|---|",
             f"| faithful | {cells[(True, True)]} | {cells[(True, False)]} |",
             f"| unfaithful | {cells[(False, True)]} | {cells[(False, False)]} |", ""]

    for case_id, label, judge, reason in disagree:
        lines.append(f"- disagree {case_id}: label {label}, judge {judge} - {reason}")

    text = "\n".join(lines)
    print(text)
    (OUT_DIR / f"agreement_{args.label}_{args.judge_version}_{args.judge_reasoning}.md").write_text(text + "\n", encoding="utf-8")


