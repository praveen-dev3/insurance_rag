def stage_retrieval(_args):

    from w12_retrieval import search_wording

    rows = []

    for claim in CLAIMS:

        truth = claim["truth"]

        if truth["boundary"] in ("lapsed",):
            continue

        product = POLICIES[claim["policy_number"]]["product"]
        in_force = editions_for_product(product, claim["loss_date"])
        query = FAMILY_QUERY[FAMILY_OF[claim["case_id"]]]
        row = {"case_id": claim["case_id"], "boundary": truth["boundary"]}

        for arm, flag in (("off", False), ("on", True)):

            result = search_wording(query, product, claim["loss_date"], top_k=3, date_filter=flag)
            matches = result["matches"]

            versioned = [m for m in matches if m["form_number"] in ("HO-0850", "MO-0420")]

            stale = [m for m in versioned if m["edition_date"] != in_force.get(m["form_number"])]

            row[arm] = {
                "hit3": (any(_is_expected(m, f, e, cl) for m in matches
                             for f, e, cl in truth["expected_cites"])
                         if truth["expected_cites"] else None),
                "stale_in_top3": len(stale),
                "stale_form_when_none_in_force": any(
                    m["form_number"] in in_force and in_force[m["form_number"]] is None
                    for m in matches),
                "top3": [(m["form_number"], m["edition_date"], m["exclusion_codes"][:1]) for m in matches],
            }

        rows.append(row)

    def rate(group, arm, key):
        subset = [r for r in rows if r["boundary"] in group and r[arm][key] is not None]
        if not subset:
            return None
        return sum(1 for r in subset if r[arm][key]), len(subset)

    lines = ["# Loss-date-aware retrieval - LLM-free, same engine, same queries, filter off vs on", "",
             "`off` = engine scoped to the product only (what retrieval did before); `on` = the in-force "
             "editions enforced by code (tools/w12_retrieval.py).", "",
             "| group | n | hit-rate@3 off | hit-rate@3 on | delta | cases with a stale-edition passage in top-3 (off -> on) |",
             "|---|---|---|---|---|---|"]

    groups = {
        "STRADDLE: loss on an older edition (pre_2025)": ("pre_2025",),
        "post_2025 (latest edition applies)": ("post_2025",),
        "base wording (single edition)": ("base",),
        "NON-straddle = post_2025 + base": ("post_2025", "base"),
        "all cases with an expected clause": ("pre_2025", "post_2025", "base"),
    }

    summary = {}

    for name, group in groups.items():

        off, on = rate(group, "off", "hit3"), rate(group, "on", "hit3")
        subset = [r for r in rows if r["boundary"] in group]
        stale_off = sum(1 for r in subset if r["off"]["stale_in_top3"])
        stale_on = sum(1 for r in subset if r["on"]["stale_in_top3"])

        if off:
            delta = on[0] / on[1] - off[0] / off[1]
            lines.append(f"| {name} | {off[1]} | {off[0]}/{off[1]} = {off[0] / off[1]:.1%} | "
                         f"{on[0]}/{on[1]} = {on[0] / on[1]:.1%} | {delta * 100:+.1f} pts | {stale_off} -> {stale_on} |")
            summary[name] = {"n": off[1], "hit3_off": off[0] / off[1], "hit3_on": on[0] / on[1],
                             "stale_off": stale_off, "stale_on": stale_on}

    none_in_force = [r for r in rows if r["boundary"] == "no_edition"]

    for r in none_in_force:
        lines += ["", f"No-edition case {r['case_id']} (loss before any HO-0850 edition took effect): "
                      f"form returned with filter off = {r['off']['stale_form_when_none_in_force']}, "
                      f"with filter on = {r['on']['stale_form_when_none_in_force']}."]

    straddle = [r for r in rows if r["boundary"] == "pre_2025"]
    lines += ["", "Per-case, straddle group (top-3 as (form, edition, first code)):", ""]

    for r in straddle:
        lines.append(f"- {r['case_id']}: off {r['off']['top3']}  ->  on {r['on']['top3']}")

    text = "\n".join(lines)
    print(text)
    (OUT_DIR / "retrieval_datefilter.md").write_text(text + "\n", encoding="utf-8")
    (OUT_DIR / "retrieval_datefilter.json").write_text(json.dumps(
        {"summary": summary, "rows": rows}, indent=2, default=str), encoding="utf-8")


